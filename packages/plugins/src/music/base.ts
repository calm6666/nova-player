/**
 * 拼接 class 字符串（过滤空值）
 *
 * @param parts - 类名片段
 * @returns 拼接后的 class
 */
export function cx(
  ...parts: Array<string | false | null | undefined>
): string {
  return parts.filter((part): part is string => Boolean(part)).join(" ");
}

