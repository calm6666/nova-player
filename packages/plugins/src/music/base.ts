/**
 * 悬浮提示：跟随鼠标展示，右侧溢出时翻转到左侧
 *
 * 采用 fixed 定位在组件内部渲染（不依赖 Portal），播放器全屏下同样正确。
 */
export const Tooltip = defineComponent<TooltipProps>(
  (props, lifecycle: ComponentLifecycle): VNode => {
    /** 是否可见 */
    const visible = signal(false);
    /** 提示层位置 */
    const position = signal({ top: 0, left: 0 });

    /** 提示层元素 */
    let tooltipEl: HTMLElement | null = null;

    /**
     * 根据鼠标位置计算提示层坐标
     *
     * @param event - 鼠标移动事件
     */
    const handleMove = (event: MouseEvent): void => {
      const popWidth = tooltipEl?.getBoundingClientRect().width || 0;
      const boundaryWidth = props.targetDom
        ? props.targetDom.getBoundingClientRect().width +
          (props.targetDom.getBoundingClientRect().left || 0)
        : window.innerWidth;
      let left = event.clientX;
      if (left + popWidth + 12 > boundaryWidth) {
        left -= popWidth + 12;
      } else {
        left += 12;
      }
      position.value = { top: event.clientY + 12, left };
    };

    // 位置同步到提示层
    onEffect(lifecycle, (): void => {
      if (!tooltipEl) return;
      const next = position.value;
      tooltipEl.style.top = `${next.top}px`;
      tooltipEl.style.left = `${next.left}px`;
    });

    return h(
      "fragment",
      {},
      h(
        "div",
        {
          style: { display: "inline-block", position: "relative" },
          onMouseEnter: (): void => {
            visible.value = true;
          },
          onMouseLeave: (): void => {
            visible.value = false;
          },
          onMouseMove: (event: Event): void => {
            if (!(event instanceof MouseEvent)) return;
            if (visible.value) {
              handleMove(event);
            }
          },
        },
        h("span", {}, ...(props.children ?? [])),
      ),
      h(
        Show,
        { when: (): boolean => visible.value },
        h(
          "div",
          {
            class: "nova-music-popover-content",
            ref: (el: unknown): void => {
              if (el instanceof HTMLElement) tooltipEl = el;
            },
          },
          // 展开数组传子节点：编译插件不会把变量 VNode 误判为响应式文本
          ...[props.content],
        ),
      ),
    );
  },
);

